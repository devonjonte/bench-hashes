const assert = require('node:assert/strict');
const { pathToFileURL } = require('node:url');
const { chromium } = require('playwright');
(async () => {
  const root = '<development-home>/bench-m6-record';
  const evidence = '<development-home>/bench-hashes-validation/ode-adler-fast';
  const browser = await chromium.launch({ executablePath: '<development-home>/.cache/ms-playwright/chromium-1193/chrome-linux/chrome', headless: true, args: ['--no-sandbox'] });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(pathToFileURL(root + '/index.html').href);
  await page.locator('#more').evaluate(e => { e.open = true; });
  await page.locator('.card').filter({ hasText: 'Apple M6' }).locator('button.use').click();
  const family = page.locator('.fam-row').filter({ has: page.locator('.fam-machine b', { hasText: 'Apple M6' }) });
  await family.waitFor({ state: 'visible' });
  assert.equal(await family.locator('.load-warning:visible').count(), 2);
  assert.match(await family.innerText(), /Library: other programs busy in 1 of 362 windows/);
  assert.match(await family.innerText(), /Files: other programs busy in 1 of 486 windows/);
  const header = page.locator('thead th').filter({ hasText: 'Apple M6' });
  assert.equal(await header.locator('.load-warning:visible').count(), 2);
  assert.match(await page.locator('tr').filter({ hasText: '1000 files, b3sum' }).innerText(), /GB\/s/);
  await page.locator('#more').evaluate(e => { e.open = false; });
  await page.screenshot({ path: evidence + '/m6-overview-qualified.png', fullPage: false });
  await page.goto(pathToFileURL(root + '/benchmark-results/AppleM6.darwin27/bench-hashes.map.html').href);
  const notes = await page.locator('.about').allTextContents();
  assert(notes.some(n => n.includes('1 of 362 windows; times may be slower')));
  assert(notes.some(n => n.includes('1 of 486 windows; times may be slower')));
  assert.equal(await page.locator('h2').filter({ hasText: 'b3sum' }).count(), 1);
  await page.locator('h2').filter({ hasText: 'b3sum' }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: evidence + '/m6-map-qualified.png', fullPage: false });
  assert.deepEqual(errors, []);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: evidence + '/m6-map-qualified-phone.png', fullPage: false });
  await browser.close();
  console.log('M6 map has both source-specific load qualifications and b3sum section; overview qualifies first view/grid/card; JS clean; desktop/phone screenshots retained');
})().catch(e => { console.error(e); process.exit(1); });
